const term = key => englishTerms[key] ?? key;
export function englishCatalogue(catalogue) {
  return {
    ...catalogue,
    facets: Object.fromEntries(Object.entries(catalogue.facets).map(([key, tags]) => [term(key), tags.map(term)])),
    categoryNotes: Object.fromEntries(Object.entries(catalogue.categoryNotes).map(([key, note]) => [term(key), notes[note] ?? note])),
    records: catalogue.records.map(record => ({
      ...record,
      category: term(record.category),
      tags: record.tags.map(term),
      note: notes[record.note] ?? record.note,
    })),
  };
}
